let groqClient: Groq | null = null;

function getGroqClient(): Groq {
  if (!groqClient) {
    if (!env.GROQ_API_KEY) {
      throw new Error('GROQ_API_KEY is not configured');
    }
    groqClient = new Groq({ apiKey: env.GROQ_API_KEY });
  }
  return groqClient;
}

async function fetchSystemContext() {
  const batches = await BatchModel.find({ status: BatchStatus.Upcoming })
    .populate('courseId', 'title')
    .select('title price startDate endDate enrollmentStartDate enrollmentEndDate status courseId')
    .sort({ startDate: 1 })
    .lean();

  const batchList = batches.map((b: any) => ({
    title: b.title,
    price: b.price,
    startDate: b.startDate
      ? new Date(b.startDate).toLocaleDateString('bn-BD', { timeZone: 'Asia/Dhaka' })
      : 'N/A',
    endDate: b.endDate
      ? new Date(b.endDate).toLocaleDateString('bn-BD', { timeZone: 'Asia/Dhaka' })
      : 'N/A',
    enrollmentStartDate: b.enrollmentStartDate
      ? new Date(b.enrollmentStartDate).toLocaleDateString('bn-BD', { timeZone: 'Asia/Dhaka' })
      : 'N/A',
    enrollmentEndDate: b.enrollmentEndDate
      ? new Date(b.enrollmentEndDate).toLocaleDateString('bn-BD', { timeZone: 'Asia/Dhaka' })
      : 'N/A',
    status: b.status,
    courseTitle: b.courseId?.title || 'N/A',
  }));

  return { batches: batchList };
}

